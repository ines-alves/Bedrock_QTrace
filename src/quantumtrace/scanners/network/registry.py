"""TLS codepoint registry access: GREASE and signalling filters plus ``kb/tls_registry.yaml``.

The registry holds names and PQC facts only, never a tier. It is generated by
``gen_registry.py`` and read here with ``yaml.safe_load``. Codepoint keys are hex strings
such as ``"0xC02F"``; the namespaces ``cipher_suites``, ``groups`` and ``signature_schemes``
are separate because one number can mean different things (0x0201 is both group MLKEM768
and signature scheme rsa_pkcs1_sha1).
"""

from __future__ import annotations

import copy
from functools import lru_cache
from pathlib import Path
from typing import Any

REGISTRY_PATH = Path(__file__).resolve().parents[2] / "kb" / "tls_registry.yaml"
KINDS = ("cipher_suites", "groups", "signature_schemes")
SIGNALLING_SUITES = frozenset({0x00FF, 0x5600})  # EMPTY_RENEGOTIATION_INFO_SCSV, FALLBACK_SCSV


def is_grease(v: int) -> bool:
    """RFC 8701 GREASE value: 0x0A0A, 0x1A1A ... 0xFAFA."""
    return (v & 0x0F0F) == 0x0A0A and (v >> 8) == (v & 0xFF)


def format_code(value: int) -> str:
    """Registry key for a 16-bit codepoint: ``0x11EC``."""
    return f"0x{value & 0xFFFF:04X}"


@lru_cache(maxsize=1)
def _load() -> dict[str, Any]:
    import yaml  # local import: purepy imports this module and stays dependency-free

    with REGISTRY_PATH.open(encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise ValueError(f"{REGISTRY_PATH} is not a mapping")
    return data


def load_registry() -> dict[str, Any]:
    """Return a private copy of the parsed registry (top keys: meta, cipher_suites, groups,
    signature_schemes, versions). Raises if the packaged file is missing or malformed."""
    return copy.deepcopy(_load())


def lookup(kind: str, code: int | str) -> dict[str, Any] | None:
    """Registry entry for ``code`` in one namespace, or None when the code is not listed."""
    if kind not in KINDS:
        raise ValueError(f"unknown registry namespace: {kind}")
    key = format_code(code) if isinstance(code, int) else format_code(int(code, 16))
    entry = _load()[kind].get(key)
    return copy.deepcopy(entry) if entry is not None else None


def iana_name(kind: str, code: int | str) -> str | None:
    """Verified IANA name for ``code``, None when the registry does not resolve it."""
    entry = lookup(kind, code)
    return entry.get("iana") if entry else None


def version_label(code: int | str) -> str | None:
    """``TLS 1.3`` style label for a protocol version codepoint, None when unknown."""
    key = format_code(code) if isinstance(code, int) else format_code(int(code, 16))
    entry = _load().get("versions", {}).get(key)
    return entry.get("label") if entry else None
